"""Build kit/scripts/script_reads.txt (the board builder's read list) from tools/trace_reads.py traces.
usage: make_script_reads.py <out.txt> <trace folder> [<trace folder> ...]   (a cold run and a warm run: their union)
One line per read: "<file prefix>: <path under Downloads/Bergama>"; a folder ends in "/"; "<prefix>: rhino" when the
script reads Rhino document objects. Left out: files the script writes itself (its own caches and results: a cold run
never needs them), and inside a folder the script also writes to (a memo cache such as cached/plants_toned/: its
entries are named by what they were made from). A folder the script lists, or reads 5 or more files from, is one "folder/" line covering its files.
A script whose run ended in an ERROR gets no lines (the builder then always runs it)."""
import sys, os, re, json, glob

out, dirs = sys.argv[1], sys.argv[2:]
per = {}
for d in dirs:
    for p in sorted(glob.glob(os.path.join(d, "traces", "*.json"))):
        t = json.load(open(p, encoding="utf-8"))
        stem = os.path.basename(p)[:-5]
        so = os.path.join(d, stem + ".stdout")
        failed = os.path.isfile(so) and "#LOG# ERROR" in open(so, encoding="utf-8", errors="replace").read()
        prefix = re.sub(r"_v\d+(_\d+)*$", "", t["script"][:-3])
        r = per.setdefault(prefix, {"reads": set(), "writes": set(), "lists": set(), "rhino": False, "failed": False})
        r["reads"] |= set(t["reads"]); r["writes"] |= set(t["writes"]); r["lists"] |= set(t["lists"])
        r["rhino"] |= t["rhino"]; r["failed"] |= failed

lines = ["# Bergama board builder: what each script reads (generated by tools/make_script_reads.py from traced test runs;",
         "# regenerate with every script update, like needed_files.txt). <file prefix>: <path under Downloads/Bergama>,",
         "# a folder ends in /, 'rhino' = reads the open Rhino model. A script with no lines here always runs.", ""]
for prefix in sorted(per):
    r = per[prefix]
    if r["failed"]:
        lines.append("# %s: no lines (its test run ended in an ERROR, so it always runs)" % prefix)
        continue
    wdirs = set(os.path.dirname(w) for w in r["writes"])
    folders = sorted(l for l in r["lists"] if l and not any(l == w or l.startswith(w + "/") for w in wdirs))
    keep = set()
    for f in r["reads"]:
        if f in r["writes"] or os.path.dirname(f) in wdirs or f.startswith("scripts/"):
            continue
        if any(f.startswith(fo + "/") for fo in folders):
            continue
        keep.add(f)
    many = {}                                     # 5 or more files read from one folder: that folder, as one line
    for f in keep:
        many.setdefault(os.path.dirname(f), []).append(f)
    for fo, fs in many.items():
        if "/" in fo and len(fs) >= 5 and fo not in folders:          # never Data/ or cached/ as a whole
            folders.append(fo)
            keep -= set(fs)
    keep = set(f for f in keep if not any(f.startswith(fo + "/") for fo in folders))
    folders = sorted(fo for fo in folders if not any(fo.startswith(o + "/") for o in folders if o != fo))
    for f in sorted(keep) + [fo + "/" for fo in folders]:
        lines.append("%s: %s" % (prefix, f))
    if r["rhino"]:
        lines.append("%s: rhino" % prefix)
open(out, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
print("%s: %d scripts, %d lines" % (out, len(per), sum(1 for l in lines if l and not l.startswith("#"))))
